import { createRequire } from 'node:module';
import { CMP_EARLY_BRIDGE_SCRIPT } from '../../mira-docs/lib/consent/cmp-early-bridge';
import { installCmpPersistenceObserver } from '../../mira-docs/lib/consent/cmp-persistence';
import { CMP_CONTROL_ENDPOINTS } from '../../mira-docs/lib/consent/config';
import { BLOG_CMP_BINDING } from '../../mira-docs/infrastructure/blog-telemetry/config';

const requireSource = createRequire(new URL('../../mira-docs/package.json', import.meta.url));
const build = await Bun.build({
  entrypoints: [new URL('./telemetry.ts', import.meta.url).pathname],
  target: 'browser', format: 'iife', minify: true,
  plugins: [{ name: 'docs-outbound-rules', setup(builder) {
    // Keep the extra search rule local to Mintlify; shared App/Blog rules are unchanged.
    builder.onResolve({ filter: /^\.\/outbound$/ }, (args) => {
      if (args.importer.endsWith('/lib/consent/outbound-gate.ts')) {
        return { path: new URL('./docs-outbound.ts', import.meta.url).pathname };
      }
    });
  } }, { name: 'sentry-browser', setup(builder) {
    builder.onResolve({ filter: /^@sentry\/nextjs$/ }, () => ({ path: requireSource.resolve('@sentry/browser') }));
  } }],
  define: { 'process.env': JSON.stringify({ NODE_ENV: 'production' }) },
});
if (!build.success) throw new AggregateError(build.logs, 'Docs telemetry build failed');
const persistence = `(${installCmpPersistenceObserver.toString()})(window,${JSON.stringify({
  settingId: BLOG_CMP_BINDING.id, settingIds: BLOG_CMP_BINDING.resolvedSettings,
  origins: CMP_CONTROL_ENDPOINTS.filter(rule => rule.methods.some(method => method === 'POST')).flatMap(rule => [...rule.origins]),
  timeoutMs: 15000,
})});`;
await Bun.write(new URL('../usercentrics.js', import.meta.url),
  '// Generated by bun scripts/build-telemetry.ts. Edit scripts/ instead.\n'
  + CMP_EARLY_BRIDGE_SCRIPT + '\n' + persistence + '\n' + await build.outputs[0].text());
console.log('Built consent-controlled Google Analytics and PostHog for Mintlify.');
